#!/usr/bin/env python3
"""Train the QL2 compressor tables from real logs: a preset dictionary (the most useful log phrases) and the Huffman code
lengths for qrlog/qrz.c. Writes qrlog/qrz_tables.h (phone/shim side) and tools/qrz_tables.py (host side); run it again only
when the log style changes, then re-run tools/test_qrl2.py.

  python3 tools/qrz-train.py [--dict N] [--unit N] FILE|DIR...      (default corpus: tools/testdata/qr-*.txt)
"""
import argparse, collections, ctypes, glob, os, re, subprocess, sys, tempfile, zlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import qrz_codec

SMOOTH = 0.25      # pseudo-count so unseen symbols stay encodable (relative to a seen-once symbol)


def corpus(paths):
    files = []
    for p in paths:
        files += sorted(glob.glob(os.path.join(p, "**", "*.txt"), recursive=True) + glob.glob(os.path.join(p, "**", "*.log"), recursive=True)) \
            if os.path.isdir(p) else [p]
    return [open(f, "rb").read() for f in files]


def build_dict(texts, size):
    """Frequent whole lines and line prefixes (up to the first digit run), scored by count*length, best LAST (closest = cheapest distance)."""
    cnt = collections.Counter()
    for t in texts:
        seen = set()
        for ln in t.split(b"\n"):
            if len(ln) < 12:
                continue
            for cand in {ln[:160], re.split(rb"[0-9]", ln, maxsplit=1)[0][:80]}:
                if len(cand) >= 12 and cand not in seen:
                    seen.add(cand)
                    cnt[cand] += 1
    cand = sorted((c for c, n in cnt.items() if n >= 2), key=lambda c: cnt[c] * len(c), reverse=True)
    out, used = [], 0
    for c in cand:
        if any(c in o for o in out):
            continue
        if used + len(c) + 1 > size:
            continue
        out.append(c)
        used += len(c) + 1
    return b"\n".join(reversed(out)) + (b"\n" if out else b"")


def write_tables(dct, lit, dist):
    def arr(name, vals, typ="uint8_t"):
        rows = [", ".join(str(v) for v in vals[i:i + 32]) for i in range(0, len(vals), 32)]
        return "static const %s %s[%d] = {\n\t%s,\n};\n" % (typ, name, len(vals), ",\n\t".join(rows))
    h = "/* GENERATED by tools/qrz-train.py - do not edit. */\n#define QRZ_DICT_LEN %du\n" % len(dct)
    h += arr("qrz_dict", list(dct) or [0]) + arr("qrz_litlen_len", lit) + arr("qrz_dist_len", dist)
    open(os.path.join(ROOT, "qrlog/qrz_tables.h"), "w").write(h)
    p = "# GENERATED by tools/qrz-train.py - do not edit.\nDICT = %r\nLITLEN_LEN = %r\nDIST_LEN = %r\n" % (bytes(dct), list(lit), list(dist))
    open(os.path.join(HERE, "qrz_tables.py"), "w").write(p)


def stats(texts, unit, dct, lit, dist):
    """Run the real C encoder (-DQRZ_STATS) over the corpus cut into units; returns (lit hist, dist hist, in bytes, out bytes, python-verified ok)."""
    write_tables(dct, lit, dist)
    d = tempfile.mkdtemp(prefix="qrz-")
    so = os.path.join(d, "qrz.so")
    subprocess.check_call(["gcc", "-O2", "-shared", "-fPIC", "-DQRZ_STATS", "-I", ROOT + "/qrlog", "-o", so, ROOT + "/qrlog/qrz.c"])
    lib = ctypes.CDLL(so)
    lib.qrz_deflate.restype = ctypes.c_uint
    hl = (ctypes.c_uint32 * 286).in_dll(lib, "qrz_hist_lit")
    hd = (ctypes.c_uint32 * 30).in_dll(lib, "qrz_hist_dist")
    tin = tout = 0
    qrz_codec.reload_tables()
    for t in texts:
        for i in range(0, len(t), unit):
            u = t[i:i + unit]
            buf = ctypes.create_string_buffer(len(u) + 64)
            n = lib.qrz_deflate(u, len(u), buf, len(buf))
            if n:
                tin += len(u); tout += n
                assert qrz_codec.inflate(buf.raw[:n]) == u, "C encoder output does not inflate to the input"
            else:
                tin += len(u); tout += len(u)
    return list(hl), list(hd), tin, tout


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("paths", nargs="*")
    ap.add_argument("--dict", type=int, default=4096)
    ap.add_argument("--unit", type=int, default=4096)
    a = ap.parse_args()
    texts = corpus(a.paths or [os.path.join(HERE, "testdata")])
    # hold out every 4th text to judge, train on the rest
    train = [t for i, t in enumerate(texts) if i % 4 != 3] or texts
    test = [t for i, t in enumerate(texts) if i % 4 == 3] or texts
    dct = build_dict(train, a.dict)
    uni = qrz_codec.package_merge([1] * 286, 15), qrz_codec.package_merge([1] * 30, 15)
    hl, hd, _, _ = stats(train, a.unit, dct, *uni)
    lit = qrz_codec.package_merge([h + SMOOTH for h in hl], 15)
    dist = qrz_codec.package_merge([h + SMOOTH for h in hd], 15)
    lit = [max(1, int(x)) for x in lit]
    _, _, tin, tout = stats(test, a.unit, dct, lit, dist)
    z = sum(len(zlib.compress(t[i:i + a.unit], 9)) for t in test for i in range(0, len(t), a.unit))
    print("dict %d B, unit %d: held-out ratio %.2f (zlib -9 dynamic, no dict: %.2f)" % (len(dct), a.unit, tin / tout, tin / z))
    # keep the tables trained on everything for the shipped result
    dct = build_dict(texts, a.dict)
    hl, hd, _, _ = stats(texts, a.unit, dct, lit, dist)
    lit = qrz_codec.package_merge([h + SMOOTH for h in hl], 15)
    dist = qrz_codec.package_merge([h + SMOOTH for h in hd], 15)
    write_tables(dct, lit, dist)
    print("wrote qrlog/qrz_tables.h, tools/qrz_tables.py")


if __name__ == "__main__":
    main()
