#!/usr/bin/env python3
"""Generate xnu/patches/0081-sweet-qr-log.patch from qrlog/ (the same sources the shim uses).

  python3 -I tools/make-qr-patch.py <xnu tree already patched through 0080> [out.patch]

Adds bsd/dev/sweet_qrcodegen.[ch] (vendored Nayuki, MIT, includes adapted to the kernel),
bsd/dev/sweet_qr.c (qrlog + the screen-takeover thread, xnu/qr/sweet_qr_thread.c.in),
registers them in bsd/conf/files, and in bsd/dev/sweet_ufs.c adds sweet_log_snapshot()
(deduped console-log tail) and the sweet_qr_start() call at the top of sweet_ufs_init().
"""
import os, re, subprocess, sys, tempfile, shutil

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tree = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(root, "xnu/patches/0081-sweet-qr-log.patch")
rd = lambda p: open(p, encoding="utf-8").read()

# --- generated kernel sources
gen = rd(os.path.join(root, "qrlog/qrcodegen.c"))
gen = gen.replace("#include <assert.h>", "#define assert(x) ((void)0)")
gen = gen.replace("#include <limits.h>", "#include <machine/limits.h>")
gen = gen.replace("#include <stdlib.h>", """static inline int qr_abs(int x) { return x < 0 ? -x : x; }
static inline long qr_labs(long x) { return x < 0 ? -x : x; }
static inline char *qr_strchr(const char *s, int c)
{
	for (;; s++) {
		if (*s == (char)c) {
			return (char *)s;
		}
		if (!*s) {
			return 0;
		}
	}
}""")
gen = gen.replace("#include <string.h>", "#include <sys/param.h>\n#include <sys/systm.h>")
gen = gen.replace('#include "qrcodegen.h"', '#include "sweet_qrcodegen.h"')
gen = re.sub(r"\blabs\(", "qr_labs(", gen)
gen = re.sub(r"\babs\(", "qr_abs(", gen)
gen = re.sub(r"\bstrchr\(", "qr_strchr(", gen)
gen = '#pragma clang diagnostic ignored "-Weverything"\n#pragma clang optimize off\t/* the kernel clang emits SHA3 vector ops (eor3) that gs101 lacks: no vectorising */\n/* Vendored Nayuki qrcodegen (MIT), kernel includes adapted by tools/make-qr-patch.py */\n' + gen
hdr = rd(os.path.join(root, "qrlog/qrcodegen.h"))

qh = rd(os.path.join(root, "qrlog/qrlog.h")).replace("#pragma once\n#include <stdint.h>\n", "")
qc = rd(os.path.join(root, "qrlog/qrlog.c")).replace('#include "qrlog.h"\n#include "qrcodegen.h"\n', "")
qr = ('''/* SWEET QR log channel (generated by tools/make-qr-patch.py from qrlog/ and xnu/qr/). */
#pragma clang diagnostic ignored "-Wcast-qual"
#pragma clang optimize off\t/* see sweet_qrcodegen.c: no auto-vectorised SHA3 ops on gs101 */
#include <sys/param.h>
#include <sys/systm.h>
#include <sys/proc.h>
#include <kern/sched_prim.h>
#include <pexpert/pexpert.h>
#include <console/video_console.h>
#include <libkern/libkern.h>
#include <stdint.h>
#include "sweet_qrcodegen.h"

extern kern_return_t kernel_thread_start(thread_continue_t, void *, thread_t *);
extern void thread_deallocate(thread_t);
extern int hz;
''' + qh + qc + rd(os.path.join(root, "xnu/qr/sweet_qr_thread.c.in")))

# --- edited existing files
ufs = rd(os.path.join(tree, "bsd/dev/sweet_ufs.c"))
a = "\tdeclare_marker\n"
snap = r'''
/*
 * Console-log tail for the QR channel (bsd/dev/sweet_qr.c): the whole ring is
 * scanned and lines that only differ in digits from one of the last 32 kept
 * lines are dropped (a root-mount retry loop would otherwise fill the tail),
 * then the last `max` bytes, starting at a line start, are returned.
 */
#define SWEET_SNAP_WORK         (48u << 10)
static char sweet_snap_work[SWEET_SNAP_WORK];

uint32_t sweet_log_snapshot(char *out, uint32_t max);

uint32_t
sweet_log_snapshot(char *out, uint32_t max)
{
	uint64_t total = os_atomic_load(&sweet_log_total, relaxed);
	uint64_t pos = total > SWEET_LOG_SIZE ? total - SWEET_LOG_SIZE : 0;
	uint32_t seen[32] = { 0 }, nseen = 0, w = 0;
	char line[160];
	uint32_t ll = 0, h = 2166136261u;

	for (; pos <= total; pos++) {
		char c = pos < total ? sweet_log_ring[pos % SWEET_LOG_SIZE] : '\n';
		if (c == '\r') {
			continue;
		}
		if (c != '\n') {
			if (ll < sizeof(line) - 1) {
				line[ll++] = c;
			}
			if (c < '0' || c > '9') {
				h = (h ^ (uint8_t)c) * 16777619u;
			}
			continue;
		}
		if (ll) {
			int dup = 0;
			for (uint32_t i = 0; i < 32 && i < nseen; i++) {
				dup |= seen[i] == h;
			}
			if (!dup) {
				seen[nseen++ % 32] = h;
				if (w + ll + 1 > SWEET_SNAP_WORK) {
					/* full: drop the oldest half, at a line start */
					uint32_t cut = SWEET_SNAP_WORK / 2;
					while (cut < w && sweet_snap_work[cut - 1] != '\n') {
						cut++;
					}
					memmove(sweet_snap_work, sweet_snap_work + cut, w - cut);
					w -= cut;
				}
				memcpy(sweet_snap_work + w, line, ll);
				w += ll;
				sweet_snap_work[w++] = '\n';
			}
		}
		ll = 0;
		h = 2166136261u;
	}
	uint32_t from = w > max ? w - max : 0;
	while (from < w && from && sweet_snap_work[from - 1] != '\n') {
		from++;
	}
	memcpy(out, sweet_snap_work + from, w - from);
	return w - from;
}
'''
m = "\nstruct sweet_log_header {"
assert m in ufs
ufs2 = ufs.replace(m, snap + m, 1)
ufs2 = ufs2.replace("static void sweet_log_start(void);\n", "static void sweet_log_start(void);\nextern void sweet_qr_start(void);\n", 1)
anchor = "sweet_ufs_init(void)\n{\n"
assert anchor in ufs2
ufs2 = ufs2.replace(anchor, anchor + "\tsweet_qr_start();\n", 1)
files = rd(os.path.join(tree, "bsd/conf/files"))
files2 = files.replace("bsd/dev/sweet_ufs.c\t\t\tstandard\n",
                       "bsd/dev/sweet_ufs.c\t\t\tstandard\nbsd/dev/sweet_qr.c\t\t\tstandard\nbsd/dev/sweet_qrcodegen.c\t\tstandard\n", 1)
assert files2 != files

# --- diff
w = tempfile.mkdtemp(prefix="qrpatch-")
def put(rel, text):
    p = os.path.join(w, rel); os.makedirs(os.path.dirname(p), exist_ok=True); open(p, "w").write(text)
for rel, new, old in (("bsd/dev/sweet_ufs.c", ufs2, ufs), ("bsd/conf/files", files2, files),
                      ("bsd/dev/sweet_qr.c", qr, None), ("bsd/dev/sweet_qrcodegen.c", gen, None),
                      ("bsd/dev/sweet_qrcodegen.h", hdr, None)):
    put("a/" + rel, old or ""); put("b/" + rel, new)
res = ""
for rel in ("bsd/conf/files", "bsd/dev/sweet_ufs.c", "bsd/dev/sweet_qr.c", "bsd/dev/sweet_qrcodegen.c", "bsd/dev/sweet_qrcodegen.h"):
    new = rel not in ("bsd/conf/files", "bsd/dev/sweet_ufs.c")
    cmd = ["diff", "-u", "--label", "/dev/null" if new else "a/" + rel, "--label", "b/" + rel,
           "/dev/null" if new else os.path.join(w, "a", rel), os.path.join(w, "b", rel)]
    r = subprocess.run(cmd, capture_output=True, text=True)
    res += r.stdout
open(out, "w").write(res)
shutil.rmtree(w)
print("wrote", out, len(res), "bytes")
