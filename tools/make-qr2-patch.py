#!/usr/bin/env python3
"""Generate xnu/patches/0094-sweet-qr-ql2.patch (QL2 QR log channel) from qrlog/ and xnu/qr/sweet_qr2_thread.c.in.

  python3 -I tools/make-qr2-patch.py <xnu tree already patched through 0093> [out.patch]

(`tools/stack-apply --keep` leaves such a tree under ~/pixelios-artifacts/scratch/.) Adds bsd/dev/sweet_qrstream.[ch], sweet_qrz.[ch],
sweet_qrz_tables.h, sweet_qrlog.h (the portable encoder, includes adapted), replaces the thread part of bsd/dev/sweet_qr.c (QL1 stays
as sweetqr_fmt=1), registers the files in bsd/conf/files, and lets AppleCLCD (SweetFramebuffer.cpp) hold off while the QR is up.
"""
import os, re, subprocess, sys, tempfile, shutil

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rd = lambda p: open(p, encoding="utf-8").read()
PRE = ('#pragma clang diagnostic ignored "-Weverything"\n'
       '#pragma clang optimize off\t/* the kernel clang emits SHA3 vector ops (eor3) that gs101 lacks: no vectorising */\n')


def conv(text, name):
    text = text.replace('#include "qrlog.h"', '#include "sweet_qrlog.h"').replace('#include "qrstream.h"', '#include "sweet_qrstream.h"')
    text = text.replace('#include "qrz.h"', '#include "sweet_qrz.h"').replace('#include "qrz_tables.h"', '#include "sweet_qrz_tables.h"')
    text = text.replace('#include "qrcodegen.h"', '#include "sweet_qrcodegen.h"')
    return "/* %s: generated by tools/make-qr2-patch.py from qrlog/%s */\n" % (name, name.replace("sweet_", "", 1)) + PRE + text


def new_files():
    """{path in the xnu tree: content} of the files the patch adds (tools/test_qrl2.py checks the committed patch against this)."""
    new = {}
    for src, dst in (("qrstream.c", "sweet_qrstream.c"), ("qrz.c", "sweet_qrz.c")):
        new["bsd/dev/" + dst] = conv(rd(os.path.join(root, "qrlog", src)), dst)
    for src, dst in (("qrstream.h", "sweet_qrstream.h"), ("qrz.h", "sweet_qrz.h"), ("qrz_tables.h", "sweet_qrz_tables.h"), ("qrlog.h", "sweet_qrlog.h")):
        t = rd(os.path.join(root, "qrlog", src))
        new["bsd/dev/" + dst] = t.replace("#pragma once\n", "#pragma once\n/* generated by tools/make-qr2-patch.py from qrlog/%s */\n" % src, 1) if "#pragma once" in t \
            else "/* generated by tools/make-qr2-patch.py from qrlog/%s */\n" % src + t
    return new


def main(tree, out):
    new = new_files()
    # --- edited existing files
    qr_old = rd(os.path.join(tree, "bsd/dev/sweet_qr.c"))
    marker = "/* ---- kernel side: take over the screen"
    assert marker in qr_old
    inc = '#include "sweet_qrcodegen.h"\n'
    assert inc in qr_old
    qr_new = qr_old[:qr_old.index(marker)].replace(inc, "#include <kern/clock.h>\n#include <mach/mach_time.h>\n" + inc + '#include "sweet_qrstream.h"\n', 1) \
        + rd(os.path.join(root, "xnu/qr/sweet_qr2_thread.c.in"))
    files_old = rd(os.path.join(tree, "bsd/conf/files"))
    anchor = "bsd/dev/sweet_qrcodegen.c\t\tstandard\n"
    assert anchor in files_old
    files_new = files_old.replace(anchor, anchor + "".join("bsd/dev/%s\t\tstandard\n" % f for f in ("sweet_qrstream.c", "sweet_qrz.c")), 1)
    fb_old = rd(os.path.join(tree, "iokit/Kernel/arm/SweetFramebuffer.cpp"))
    a1 = 'extern "C" int sweet_console_muted;     /* osfmk/console/serial_console.c */\n'
    a2 = "\tif (fb->fPowerOff) {\n\t\t/* Fade out:"
    assert a1 in fb_old and a2 in fb_old
    fb_new = fb_old.replace(a1, a1 + 'extern "C" int sweet_qr_hold;          /* bsd/dev/sweet_qr.c: the QR log is on screen */\n', 1)
    fb_new = fb_new.replace(a2, "\tif (sweet_qr_hold) {\n\t\t/* the QR log owns the panel: no present(), no fade (vsync notifications keep flowing) */\n"
                            "\t\tIOLockUnlock(fb->fLock);\n\t\tsender->setTimeoutUS(SWEET_FB_VSYNC_US);\n\t\treturn;\n\t}\n" + a2, 1)

    # --- diff
    w = tempfile.mkdtemp(prefix="qr2patch-")


    def put(rel, text):
        p = os.path.join(w, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, "w").write(text)


    edits = [("bsd/conf/files", files_new, files_old), ("bsd/dev/sweet_qr.c", qr_new, qr_old),
             ("iokit/Kernel/arm/SweetFramebuffer.cpp", fb_new, fb_old)] + [(k, v, None) for k, v in sorted(new.items())]
    res = ""
    for rel, nt, ot in edits:
        put("a/" + rel, ot or "")
        put("b/" + rel, nt)
        fresh = ot is None
        r = subprocess.run(["diff", "-u", "--label", "/dev/null" if fresh else "a/" + rel, "--label", "b/" + rel,
                            "/dev/null" if fresh else os.path.join(w, "a", rel), os.path.join(w, "b", rel)], capture_output=True, text=True)
        res += r.stdout
    open(out, "w").write(res)
    shutil.rmtree(w)
    print("wrote", out, len(res), "bytes")


if __name__ == "__main__":
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(root, "xnu/patches/0094-sweet-qr-ql2.patch")
    main(sys.argv[1], out)
