"""QL2 compression layer, host side: rebuilds the deflate block header the phone does not send (qrlog/qrz.h) and inflates
with the python stdlib. Tables (preset dictionary + Huffman code lengths) come from tools/qrz_tables.py, generated by
tools/qrz-train.py together with qrlog/qrz_tables.h."""
import os, sys, zlib

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import qrz_tables as T

CL_ORDER = [16, 17, 18, 0, 8, 7, 9, 6, 10, 5, 11, 4, 12, 3, 13, 2, 14, 1, 15]


def package_merge(freqs, limit):
    """Optimal Huffman code lengths <= limit for freqs (all > 0): a complete prefix code."""
    leaves = sorted((f, (i,)) for i, f in enumerate(freqs))
    cur = leaves
    for _ in range(limit - 1):
        pk = [(cur[2 * k][0] + cur[2 * k + 1][0], cur[2 * k][1] + cur[2 * k + 1][1]) for k in range(len(cur) // 2)]
        cur = sorted(leaves + pk, key=lambda x: x[0])
    lens = [0] * len(freqs)
    for _, syms in cur[:2 * (len(freqs) - 1)]:
        for s in syms:
            lens[s] += 1
    return lens


def _canon(lens):
    cnt = [0] * 16
    for l in lens:
        cnt[l] += 1
    cnt[0] = 0
    nxt, c = [0] * 16, 0
    for b in range(1, 16):
        c = (c + cnt[b - 1]) << 1
        nxt[b] = c
    out = []
    for l in lens:
        out.append((nxt[l], l) if l else (0, 0))
        if l:
            nxt[l] += 1
    return out


def header_bits(lit_lens, dist_lens):
    """(value, nbits): the dynamic block header (BFINAL=1) for these code lengths, no run-length codes (never transmitted, so its size is free).
    The code-length alphabet uses a fixed complete code: 13 symbols of 4 bits, 6 of 5 bits."""
    cl_len = [4] * 13 + [5] * 6
    cl = _canon(cl_len)
    v, n = 0, 0

    def put(x, k):          # LSB-first field
        nonlocal v, n
        v |= x << n
        n += k

    def put_code(sym):      # Huffman code: MSB first
        nonlocal v, n
        code, l = cl[sym]
        for i in range(l):
            v |= ((code >> (l - 1 - i)) & 1) << (n + i)
        n += l
    put(1, 1); put(2, 2)
    put(len(lit_lens) - 257, 5); put(len(dist_lens) - 1, 5); put(19 - 4, 4)
    for s in CL_ORDER:
        put(cl_len[s], 3)
    for l in list(lit_lens) + list(dist_lens):
        put_code(l)
    return v, n


_HDR = None


def reload_tables():
    """After qrz-train.py rewrote qrz_tables.py in this process."""
    global _HDR
    import importlib
    importlib.reload(T)
    _HDR = None


def inflate(payload, ulen=None):
    """Body bits from qrz_deflate (C) -> raw bytes."""
    global _HDR
    if _HDR is None:
        _HDR = header_bits(T.LITLEN_LEN, T.DIST_LEN)
    hv, hn = _HDR
    v = hv | (int.from_bytes(payload, "little") << hn)
    stream = v.to_bytes((hn + 8 * len(payload) + 7) // 8, "little")
    d = zlib.decompressobj(-15, zdict=T.DICT) if T.DICT else zlib.decompressobj(-15)
    out = d.decompress(stream)
    if not d.eof:
        raise ValueError("deflate stream incomplete")
    return out
